const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
let nodes = {};
const node = id => nodes[id] ||= {value:'',checked:false,dataset:{},querySelectorAll:()=>[],remove(){},focus(){}};
const ctx = vm.createContext({setTimeout(){},clearTimeout(){},localStorage:{getItem:()=>null,setItem(){}},document:{querySelector:node,querySelectorAll:()=>[]}});
for (const file of ['config','auth','utils','rules','lots','records','ui']) vm.runInContext(fs.readFileSync((file==='demo'?`${__dirname}/fixtures/demo.js`:`${__dirname}/../dist/js/${file}.js`),'utf8'),ctx);
const run = code => vm.runInContext(code,ctx);
run("signedIn=true;currentRole='operador'");
const render = () => {nodes={};run("tab='sessao';render()");};
render();
node('#vaccinated').checked=true;node('#vaccinated').onchange();
assert.equal(node('#vfields').hidden,false);
node('#vname').value='Vacina teste';node('#next').value='2026-12-01';
node('#repeat-vaccine').checked=true;node('#repeat-vaccine').onchange();
node('#day').value='2026-10-03';node('#day').onchange();
render(); // Próximo animal sem vacinação não deve apagar a preferência.
assert.equal(node('#vaccinated').checked,false);
node('#vaccinated').onchange();
assert.equal(run('db.sessionVaccine.name'),'Vacina teste');
render();
assert.match(node('#view').innerHTML,/value="2026-10-03"/);
node('#vaccinated').checked=true;node('#vaccinated').onchange();
assert.equal(node('#vname').value,'Vacina teste');
assert.equal(run('db.sessionVaccine.day'),undefined);
assert.doesNotMatch(node('#view').innerHTML, /id="vday"/);
assert.equal(node('#next').value,'2026-12-01');
run("modal=()=>{};db.session=[{id:'A',kg:300,day:'2026-10-03'}];sessionRows()");
node('#finish').onclick();
assert.equal(run('db.sessionVaccine'),undefined);
assert.equal(run('db.lastWeighingDay'),'2026-10-03');
assert.equal(node('#repeat-vaccine').checked,false);
console.log('Sessão: vacina repetida após animal não vacinado, data mantida e preferência limpa ao finalizar.');
run("tab='sessao'");
assert.doesNotMatch(run('profileFields()'), /id="from"/);
assert.match(run('profileFields()'), /id="origin-field" hidden/);
assert.equal(run("profileUpdates({origin:'Compra',from:'Fazenda A'},{age:'12'},true).origin"),undefined);
assert.equal(run("profileUpdates({origin:'Compra',from:'Fazenda A'},{age:'12'},true).from"),undefined);
run("tab='individual'");
assert.match(run('profileFields()'), /id="origin"/);
assert.match(run('profileFields()'), /id="from"/);

run("tab='sessao'");
assert.doesNotMatch(run('profileFields()'), /id="arrival"/);
assert.match(run('profileFields()'), /Preço do kg de entrada \(R\$\)/);
assert.equal(run("profileUpdates({arrival:'2026-01-01'},{age:'12'},true).arrival"),undefined);
run("tab='individual'");
assert.match(run('profileFields()'), /id="arrival"/);
